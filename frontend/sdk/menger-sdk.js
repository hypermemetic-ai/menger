  // Find the section again (a script may have drawn it, or moved it) and
  // mark it and its ancestors — through shadow roots, up to <html>.
  function isolate() {
    if (!citeTarget) return null;
    var el = findSection(citeTarget);
    if (el === citeEl && (!el || el.hasAttribute(CITE_SHOWN))) return el;
    unmark();
    citeEl = el;
    if (!el) return null;
    el.setAttribute(CITE_SHOWN, "");
    var n = el;
    while (n) {
      var up = n.parentNode;
      if (up && up.nodeType === 11 && up.host) up = up.host; // a shadow root: on to its host
      if (!up || up.nodeType !== 1) break;
      up.setAttribute(CITE_PATH, "");
      n = up;
    }
    return el;
  }

