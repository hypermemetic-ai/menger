  function placeTip() {
    if (!tip || !tip.st || !tip.st.badge) return;
    var host = tip.host;
    // Under the instance (never over it), left-aligned with its badge — or
    // above the badge where there is no room below.
    var r = tip.st.badge.getBoundingClientRect();
    var under = tip.el.getBoundingClientRect();
    var sx = window.scrollX || 0;
    var sy = window.scrollY || 0;
    host.setAttribute("style", "all:initial;display:block;position:absolute;z-index:2147483647;left:0;top:0;visibility:hidden");
    var w = host.offsetWidth;
    var h = host.offsetHeight;
    var docW = doc.documentElement.clientWidth || w;
    var content = contentHeight();
    var left = Math.max(2, Math.min(r.left + sx, docW - w - 2));
    var below = Math.max(r.bottom, under.bottom) + sy + 4;
    var above = r.top + sy - h - 4;
    var top = below + h <= content || above < 0 ? below : above;
    tipBottom = top + h + 4 > content ? Math.ceil(top + h + 4) : 0;
    host.setAttribute(
      "style",
      "all:initial;display:block;position:absolute;z-index:2147483647;left:" + Math.round(left) + "px;top:" + Math.round(top) + "px"
    );
    report(false);
  }

  function openTip(target, st) {
    // COMMENT-3: the info card is annotation mode's.
    if (!annotating) return;
    var t = tipParts();
    clearTimeout(tipTimer);
    if (t.st && t.st !== st && t.st.badge) t.st.badge.classList.remove("open");
    t.el = target;
    t.st = st;
    if (st.badge) st.badge.classList.add("open");
    fillTip(t.box, st.name, null);
    placeTip();
    inspectEl(target, st.name).then(function (insp) {
      if (!tip || tip.el !== target) return;
      if (st.badge) st.badge.classList.toggle("flagged", !!(insp && insp.flagged));
      fillTip(tip.box, st.name, insp);
      placeTip();
    });
  }

  function closeSoon() {
    clearTimeout(tipTimer);
    tipTimer = setTimeout(closeTip, 250);
  }

  function closeTip() {
    clearTimeout(tipTimer);
    if (!tip || !tip.el) return;
    if (tip.st && tip.st.badge) tip.st.badge.classList.remove("open");
    tip.el = null;
    tip.st = null;
    hideTip();
    tipBottom = 0;
    report(false);
  }

