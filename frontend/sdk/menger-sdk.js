  // -- annotation mode (COMMENT-3) ---------------------------------------------
  // The host's mode, reaching into the body. What an element *is* — its
  // path, its label — the host decides from the chain posted here
  // (src/anchor.rs); this side reads the DOM, outlines, and keeps clicks.

  var ANNOT_CSS =
    "*{outline:var(--border) dashed var(--annot)!important;outline-offset:-1px!important;cursor:crosshair!important}" +
    "[data-menger-tip]{outline:0!important;cursor:auto!important}";
  var annotStyle = null;
  var hovered = null;
  var picked = Object.create(null);
  var nextPick = 0;

  function inTip(ev) {
    var path = ev.composedPath ? ev.composedPath() : [ev.target];
    for (var i = 0; i < path.length; i++) {
      var n = path[i];
      if (n && n.nodeType === 1 && n.hasAttribute("data-menger-tip")) return true;
    }
    return false;
  }

  function words(t, max) {
    return String(t || "").replace(/\s+/g, " ").trim().slice(0, max);
  }

  function textOf(el) {
    var t = typeof el.innerText === "string" ? el.innerText : el.textContent;
    return String(t || "").slice(0, 600);
  }

  function rectOf(el) {
    var r = el.getBoundingClientRect();
    return { x: r.left, y: r.top, w: r.width, h: r.height };
  }

  // What names an element on the page: a <dd>'s <dt>, a cell's column
  // header, a section's heading.
  function captionOf(n) {
    var tag = n.localName;
    if (tag === "dd") {
      var dt = n.previousElementSibling;
      return dt && dt.localName === "dt" ? words(dt.textContent, 60) || null : null;
    }
    if (tag === "td" || tag === "th") {
      var row = n.parentElement;
      if (!row || (row.parentElement && row.parentElement.localName === "thead")) return null;
      var at = Array.prototype.indexOf.call(row.children, n);
      var table = n.closest("table");
      var head = table && table.querySelector("thead tr");
      var h = head && head.children[at];
      return h ? words(h.textContent, 60) || null : null;
    }
    if (tag === "section" || tag === "article" || tag === "aside" || tag === "details") {
      var hd = n.querySelector(":scope > h1, :scope > h2, :scope > h3, :scope > h4, :scope > summary");
      return hd ? words(hd.textContent, 60) || null : null;
    }
    return null;
  }

  function nodeOf(n) {
    var attrs = [];
    for (var i = 0; i < n.attributes.length && attrs.length < 24; i++) {
      var a = n.attributes[i];
      if (a.name !== "class" && a.name !== "style") attrs.push([a.name, a.value.slice(0, 300)]);
    }
    var nth = 1;
    var of = 0;
    var parent = n.parentElement;
    if (parent) {
      for (var s = parent.firstElementChild; s; s = s.nextElementSibling) {
        if (s.localName === n.localName) {
          of++;
          if (s === n) nth = of;
        }
      }
    }
    return {
      tag: n.localName,
      attrs: attrs,
      classes: Array.prototype.slice.call(n.classList, 0, 8),
      nth: nth,
      of: Math.max(of, 1),
      caption: captionOf(n),
    };
  }

  // The element, then its ancestors below the body element.
  function chainOf(el) {
    var out = [];
    for (var n = el; n && n.nodeType === 1 && n !== doc.body && n !== doc.documentElement && out.length < 32; n = n.parentElement) {
      out.push(nodeOf(n));
    }
    return out;
  }

  function isPage(el) {
    return !el || el.nodeType !== 1 || el === doc.body || el === doc.documentElement;
  }

  // The innermost component instance on the event's path.
  function componentOf(ev) {
    var path = ev.composedPath ? ev.composedPath() : [ev.target];
    for (var i = 0; i < path.length; i++) {
      var st = path[i] && path[i].nodeType === 1 ? states.get(path[i]) : null;
      if (st) return { el: path[i], st: st };
    }
    return null;
  }

