  var inspections = Object.create(null);
  var nextInspect = 0;

  // What the host says about this instance — null when it does not answer.
  function inspectEl(el, name) {
    return new Promise(function (resolve) {
      var id = ++nextInspect;
      inspections[id] = resolve;
      var attrs = [];
      for (var i = 0; i < el.attributes.length; i++) attrs.push([el.attributes[i].name, el.attributes[i].value]);
      post("menger:inspect", { id: id, name: name, attrs: attrs });
      setTimeout(function () {
        if (inspections[id]) {
          delete inspections[id];
          resolve(null);
        }
      }, 5000);
    });
  }

  function inspected(m) {
    var resolve = inspections[m.id];
    if (!resolve) return;
    delete inspections[m.id];
    resolve(m.inspection && typeof m.inspection === "object" ? m.inspection : null);
  }

  function follow(el, st, which) {
    inspectEl(el, st.name).then(function (insp) {
      if (insp && typeof insp[which] === "string") navigate(insp[which]);
    });
  }

  // COMMENT-3: whether the host's annotation mode is on.
