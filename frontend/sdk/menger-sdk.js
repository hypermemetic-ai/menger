    for (; el; el = el.parentNode || el.host) path.push(el);
    var chip = chipOf(path);
    if (!chip) return;
    ev.preventDefault();
    var r = chip.el.getBoundingClientRect();
    menuFocus = path[0];
    post("menger:ticket-menu", { id: chip.id, x: r.left, y: r.bottom, keyboard: true });
