  // Every pointer and mouse event is the mode's: stopped before anything of
  // the body's hears it (capture, on the window: first), its default
  // prevented (a pointer event's is left alone — its mouse events are
  // stopped instead). The info card's own links stay live.
  ["pointerdown", "pointerup", "mousedown", "mouseup", "click", "dblclick", "auxclick", "contextmenu"].forEach(function (type) {
    window.addEventListener(
      type,
      function (ev) {
        if (!annotating || inTip(ev)) return;
        ev.stopImmediatePropagation();
        if (type.indexOf("pointer") === 0) return;
        ev.preventDefault();
        if (type !== "click" || isPage(ev.target)) return;
        var id = ++nextPick;
        picked[id] = ev.target;
        post("menger:pick", { id: id, chain: chainOf(ev.target), rect: rectOf(ev.target), text: textOf(ev.target) });
      },
      true
    );
  });

  function probe(m) {
    var el = picked[m.id];
    delete picked[m.id];
    var sels = Array.isArray(m.selectors) ? m.selectors : [];
    var ok = sels.map(function (sel) {
      try {
        var all = doc.querySelectorAll(String(sel));
        return !!el && all.length === 1 && all[0] === el;
      } catch (e) {
        return false;
      }
    });
    post("menger:probed", { id: m.id, ok: ok });
  }

  function locate(m) {
    var paths = Array.isArray(m.paths) ? m.paths : [];
    var found = paths.map(function (p) {
      try {
        var el = doc.querySelector(String(p));
        return el ? { rect: rectOf(el), text: textOf(el) } : null;
      } catch (e) {
        return null;
      }
    });
    post("menger:located", { id: m.id, found: found });
  }

  // MENGER-6: ⌘K (Ctrl+K off a Mac) is the app's palette, from anywhere in
  // the body, a field included — taken before the body's own handlers, so
